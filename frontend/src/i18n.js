export function translate(code, key, params) {
  const table = STRINGS[code] ?? STRINGS.en
  let text = table[key] ?? STRINGS.en[key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

